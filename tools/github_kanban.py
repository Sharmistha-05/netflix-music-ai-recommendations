"""Build the Netflix Music Kanban board as a GitHub Project (Projects v2).

    python tools/github_kanban.py OWNER/REPO ["Project title"]

Needs the GitHub CLI (`gh`) signed in with the `project` and `repo` scopes.
It creates, from Sheet 2 - Sprint Tasks plus the 7 cards named in the brief:
  * labels   priority: High / Medium / Low, source: Sheet 2 / brief
  * issues   one per task (17), owner, priority and WSJF in the body;
             tasks already Completed are closed as completed
  * project  linked to the repo, Status options Backlog / In Progress / Completed,
             extra fields Priority, WSJF and Owner, items in WSJF order
The project's board layout itself is switched on in the GitHub UI (the API
cannot create views).
"""
import json
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import analysis as A  # noqa: E402

LABELS = {
    "priority: High": ("E50914", "High priority (Sheet 2)"),
    "priority: Medium": ("F2A900", "Medium priority (Sheet 2)"),
    "priority: Low": ("3A9D5D", "Low priority (Sheet 2)"),
    "source: Sheet 2": ("5F5F5F", "Task from CEP_Dataset.xlsx, Sheet 2 - Sprint Tasks"),
    "source: brief": ("1D76DB", "Card named in the course-end project brief"),
}
STATUS = [("Backlog", "GRAY", "Prioritized by WSJF; top item is pulled next"),
          ("In Progress", "YELLOW", "WIP limit 5"),
          ("Completed", "GREEN", "Meets the Definition of Done")]


def gh(*args, parse=False):
    out = subprocess.run(["gh", *args], check=True, capture_output=True, text=True).stdout
    return json.loads(out) if parse else out.strip()


def graphql(query, **variables):
    args = ["api", "graphql", "-f", f"query={query}"]
    for k, v in variables.items():
        args += ["-F" if isinstance(v, (int, float)) else "-f", f"{k}={v}"]
    return gh(*args, parse=True)


def issue_body(card, wsjf_row):
    lines = [f"**Task ID:** {card.task_id}", f"**Owner:** {card.owner}", f"**Priority:** {card.priority}",
             f"**Kanban list:** {card.status}", f"**Source:** {card.source}", ""]
    if wsjf_row is not None:
        lines += ["### WSJF (backlog prioritization)", "",
                  "| Business value | Time criticality | Risk reduction | Job size | WSJF | Backlog rank |",
                  "| --- | --- | --- | --- | --- | --- |",
                  f"| {wsjf_row.business_value} | {wsjf_row.time_criticality} | {wsjf_row.risk_reduction} | "
                  f"{wsjf_row.job_size} | {wsjf_row.wsjf:.2f} | #{wsjf_row.backlog_rank} |", "",
                  f"Why: {wsjf_row.rationale}", ""]
    lines += ["### Definition of Done", "", "- [ ] Code reviewed", "- [ ] Tests pass and Postman checks green",
              "- [ ] Metrics dashboard updated", "- [ ] Accepted by the Product Manager", "",
              "_Generated by tools/github_kanban.py from CEP_Dataset.xlsx._"]
    return "\n".join(lines)


def main(repo, title):
    owner = repo.split("/")[0]
    board = A.board(A.load_tasks())
    wsjf = A.wsjf_table().set_index("card")

    # ---- labels
    for name, (color, desc) in LABELS.items():
        gh("label", "create", name, "--repo", repo, "--color", color, "--description", desc, "--force")

    # ---- order: Backlog by WSJF rank, then In Progress and Completed by priority
    pri = {"High": 0, "Medium": 1, "Low": 2}
    board["order"] = [(0, wsjf.loc[t, "backlog_rank"]) if s == "Backlog" else
                      ({"In Progress": 1, "Completed": 2}[s], pri[p] * 100 + i)
                      for i, (t, s, p) in enumerate(zip(board.task_id, board.status, board.priority))]
    board = board.sort_values("order").reset_index(drop=True)

    # ---- issues
    urls = {}
    for card in board.itertuples():
        w = wsjf.loc[card.task_id] if card.task_id in wsjf.index else None
        labels = f"priority: {card.priority},source: {'Sheet 2' if card.source == 'Sheet 2' else 'brief'}"
        url = gh("issue", "create", "--repo", repo, "--title", f"{card.task_id} {card.task_name}",
                 "--body", issue_body(card, w), "--label", labels)
        if card.status == "Completed":
            gh("issue", "close", url, "--repo", repo, "--reason", "completed")
        urls[card.task_id] = url
        print("issue", card.task_id, url)

    # ---- project
    proj = gh("project", "create", "--owner", owner, "--title", title, "--format", "json", parse=True)
    num, pid = proj["number"], proj["id"]
    gh("project", "link", str(num), "--owner", owner, "--repo", repo)
    gh("project", "edit", str(num), "--owner", owner, "--readme",
       "Kanban for the Netflix Music AI recommendations course-end project. Lists: Backlog (WSJF order), "
       "In Progress (WIP limit 5), Completed. Built from CEP_Dataset.xlsx Sheet 2 plus the brief's cards.",
       "--description", "Sprint Kanban: Backlog, In Progress, Completed")

    fields = gh("project", "field-list", str(num), "--owner", owner, "--format", "json", parse=True)["fields"]
    status_id = next(f["id"] for f in fields if f["name"] == "Status")
    opts = ", ".join(f'{{name: "{n}", color: {c}, description: "{d}"}}' for n, c, d in STATUS)
    res = graphql("mutation($id: ID!) { updateProjectV2Field(input: {fieldId: $id, singleSelectOptions: [%s]}) "
                  "{ projectV2Field { ... on ProjectV2SingleSelectField { options { id name } } } } }" % opts,
                  id=status_id)
    status_opt = {o["name"]: o["id"] for o in res["data"]["updateProjectV2Field"]["projectV2Field"]["options"]}

    prio = gh("project", "field-create", str(num), "--owner", owner, "--name", "Priority", "--data-type",
              "SINGLE_SELECT", "--single-select-options", "High,Medium,Low", "--format", "json", parse=True)
    prio_opt = {o["name"]: o["id"] for o in prio["options"]}
    wsjf_f = gh("project", "field-create", str(num), "--owner", owner, "--name", "WSJF", "--data-type", "NUMBER",
                "--format", "json", parse=True)
    owner_f = gh("project", "field-create", str(num), "--owner", owner, "--name", "Owner", "--data-type", "TEXT",
                 "--format", "json", parse=True)

    # ---- items, added in board order
    for card in board.itertuples():
        item = gh("project", "item-add", str(num), "--owner", owner, "--url", urls[card.task_id],
                  "--format", "json", parse=True)["id"]
        edit = ["project", "item-edit", "--id", item, "--project-id", pid]
        gh(*edit, "--field-id", status_id, "--single-select-option-id", status_opt[card.status])
        gh(*edit, "--field-id", prio["id"], "--single-select-option-id", prio_opt[card.priority])
        gh(*edit, "--field-id", owner_f["id"], "--text", card.owner)
        if card.task_id in wsjf.index:
            gh(*edit, "--field-id", wsjf_f["id"], "--number", str(wsjf.loc[card.task_id, "wsjf"]))
        print("item", card.task_id, card.status)

    print(json.dumps({"project_number": num, "project_url": proj.get("url"), "issues": len(urls)}))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "Netflix Music: AI Recommendations Kanban")
